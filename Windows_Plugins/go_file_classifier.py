def _normalize_filepath(filepath: str) -> str:
    """
    Normalize a Go source file path by stripping absolute path prefixes.
    
    Handles:
    - /home/user/go/src/runtime/proc.go -> runtime/proc.go
    - /usr/local/go/src/net/http/server.go -> net/http/server.go
    - /home/user/go/pkg/mod/github.com/foo/bar@v1.0.0/baz.go -> github.com/foo/bar/baz.go
    - C:\\Users\\user\\go\\src\\runtime\\proc.go -> runtime/proc.go
    
    Args:
        filepath: Raw file path from pclntab
        
    Returns:
        Normalized relative path
    """
    if not filepath:
        return filepath
    
    # Normalize slashes
    filepath = filepath.replace('\\', '/')
    
    # Strip leading slashes
    filepath = filepath.lstrip('/')
    
    # Pattern 1: Go SDK source path
    # Matches: anything/go/src/package/...
    # Also matches: anything/go1.XX/src/package/...
    # Also matches: anything/sdk/go1.XX/src/package/...
    sdk_patterns = [
        r'^.*/go\d*\.?\d*\.?\d*/src/(.+)$',  # go1.21.5/src/...
        r'^.*/sdk/go\d+\.\d+\.?\d*/src/(.+)$',  # sdk/go1.21/src/...
        r'^.*/go/src/(.+)$',  # go/src/...
        r'^.+/src/((?:runtime|internal|syscall|reflect|sync|crypto|net|os|io|fmt|errors|context|time|strings|bytes|bufio|strconv|unicode|sort|container|encoding|compress|archive|debug|go|hash|html|image|index|log|math|mime|path|plugin|regexp|testing|text|embed|maps|slices|cmp|iter|unique|weak|structs|database|expvar|flag)/.+)$',
    ]
    
    for pattern in sdk_patterns:
        match = re.match(pattern, filepath, re.IGNORECASE)
        if match:
            return match.group(1)
    
    # Pattern 2: GOPATH/pkg/mod (module cache)
    # Matches: anything/go/pkg/mod/github.com/user/repo@v1.2.3/file.go
    mod_match = re.match(r'^.*/go/pkg/mod/(.+)$', filepath, re.IGNORECASE)
    if mod_match:
        mod_path = mod_match.group(1)
        # Remove version suffix: github.com/foo/bar@v1.0.0/... -> github.com/foo/bar/...
        mod_path = re.sub(r'@v[^/]+/', '/', mod_path)
        # Handle !uppercase encoding in module paths
        # e.g., !azure -> Azure
        mod_path = re.sub(r'!([a-z])', lambda m: m.group(1).upper(), mod_path)
        return mod_path
    
    # Pattern 3: GOPATH/src (pre-modules)
    # Matches: anything/gopath/src/github.com/...
    gopath_match = re.match(r'^.*/(?:gopath|GOPATH)/src/(.+)$', filepath, re.IGNORECASE)
    if gopath_match:
        return gopath_match.group(1)
    
    # Pattern 4: Bazel-style paths
    # Matches: bazel-out/k8-fastbuild/bin/external/com_github_foo_bar/...
    bazel_match = re.match(r'^.*bazel[^/]*/[^/]+/bin/(?:external/)?(.+)$', filepath, re.IGNORECASE)
    if bazel_match:
        bazel_path = bazel_match.group(1)
        # Convert com_github_foo_bar to github.com/foo/bar
        bazel_path = re.sub(r'^com_github_([^/]+)_([^/]+)', r'github.com/\1/\2', bazel_path)
        bazel_path = re.sub(r'^org_golang_', 'golang.org/', bazel_path)
        bazel_path = re.sub(r'^io_k8s_', 'k8s.io/', bazel_path)
        return bazel_path
    
    # Pattern 5: _gomod_ prefix (Go module builds)
    if filepath.startswith('_gomod_/'):
        return filepath[8:]
    
    # Pattern 6: command-line-arguments (main package)
    if filepath.startswith('command-line-arguments/'):
        return filepath
    
    # Pattern 7: Nix store paths
    # /nix/store/xxx-go-1.21/share/go/src/...
    nix_match = re.match(r'^nix/store/[^/]+-go[^/]*/share/go/src/(.+)$', filepath, re.IGNORECASE)
    if nix_match:
        return nix_match.group(1)
    
    # Pattern 8: Generic - try to find stdlib package at any depth
    # Look for stdlib top-level package in the path
    parts = filepath.split('/')
    for i, part in enumerate(parts):
        if part in STDLIB_TOP_LEVEL:
            # Check if this looks like the start of the real path
            remaining = '/'.join(parts[i:])
            # Validate it ends with .go or contains typical file structure
            if remaining.endswith('.go') or '/' in remaining:
                return remaining
    
    return filepath


def _is_valid_domain(segment: str) -> bool:
    """
    Check if a path segment looks like a valid domain name.
    
    Args:
        segment: First segment of a path
        
    Returns:
        True if it looks like a domain (e.g., github.com, example.io)
    """
    if not segment or len(segment) < 4:  # Minimum: a.io
        return False
    
    # Must contain a dot
    if '.' not in segment:
        return False
    
    # Split into parts
    parts = segment.split('.')
    if len(parts) < 2:
        return False
    
    # TLD check
    tld = parts[-1].lower()
    if tld not in GO_MODULE_TLDS:
        return False
    
    # Domain name validation (alphanumeric and hyphens)
    for part in parts:
        if not part:
            return False
        if not re.match(r'^[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?$', part):
            return False
    
    return True


def _check_internal_package(filepath: str, package: str) -> Optional[str]:
    """
    Check if a filepath belongs to an internal package.
    
    Args:
        filepath: Normalized file path
        package: Package path (directory)
        
    Returns:
        Category string or None
    """
    # Check runtime internal first (more specific)
    for prefix in RUNTIME_INTERNAL_PREFIXES:
        if filepath.startswith(prefix + '/') or package == prefix:
            return FileCategory.RUNTIME_INTERNAL.value
    
    # Check stdlib internal
    for prefix in STDLIB_INTERNAL_PREFIXES:
        if filepath.startswith(prefix + '/') or package == prefix:
            return FileCategory.STDLIB_INTERNAL.value
    
    # Generic internal/ - default to stdlib internal
    if filepath.startswith('internal/'):
        return FileCategory.STDLIB_INTERNAL.value
    
    return None


def classify_go_filepath(filepath: str) -> Dict:
    """
    Classify a Go source file path into categories.
    """
    # Handle special cases
    if not filepath or filepath == "<unknown>":
        return {'category': FileCategory.UNKNOWN.value, 'package': '', 'is_test': False}
    
    if filepath == "<autogenerated>":
        return {'category': FileCategory.AUTOGENERATED.value, 'package': '', 'is_test': False}
    
    # Normalize path
    filepath = filepath.replace('\\', '/').strip()
   
    # Remove leading slash if present
    if filepath.startswith('/'):
        filepath = filepath[1:]
    
    # ===================== NORMALIZATION BLOCK =====================
    # Strip absolute Go SDK paths: /home/user/go/src/... -> ...
    match = re.search(r'/go(?:\d+\.\d+(?:\.\d+)?)?/src/(.+)$', filepath)
    if match:
        filepath = match.group(1)
    else:
        # Try without leading slash (already stripped above)
        match = re.search(r'go(?:\d+\.\d+(?:\.\d+)?)?/src/(.+)$', filepath)
        if match:
            filepath = match.group(1)
    
    # Handle _gomod_ prefix
    if filepath.startswith('_gomod_/'):
        filepath = filepath[8:]
    # ===================== END NORMALIZATION =====================
    
    # Check if test file
    is_test = '_test.go' in filepath
    
    # === Extract package path ===
    if '/' in filepath:
        package = filepath.rsplit('/', 1)[0]
    else:
        package = ''
    
    # === Get first segment for classification ===
    first_segment = filepath.split('/')[0] if '/' in filepath else filepath
    
    # === 1. CGO and special compiler-generated ===
    if first_segment.startswith('_cgo_') or '/_cgo_' in filepath:
        return {'category': FileCategory.CGO.value, 'package': package, 'is_test': is_test}
    
    # Check for cgo-generated files
    if any(x in filepath for x in ['_cgo_gotypes.go', '_cgo_import.go', 'cgo_linux.go']):
        return {'category': FileCategory.CGO.value, 'package': package, 'is_test': is_test}
    
    # === 2. Autogenerated ===
    if first_segment == '<autogenerated>' or filepath == '<autogenerated>':
        return {'category': FileCategory.AUTOGENERATED.value, 'package': package, 'is_test': is_test}
    
    # === 3. Runtime Core ===
    if first_segment == 'runtime':
        if filepath.startswith('runtime/internal/'):
            return {'category': FileCategory.RUNTIME_INTERNAL.value, 'package': package, 'is_test': is_test}
        else:
            return {'category': FileCategory.RUNTIME_CORE.value, 'package': package, 'is_test': is_test}
    
    # === 4. Internal Packages ===
    internal_category = _check_internal_package(filepath, package)
    if internal_category:
        return {'category': internal_category, 'package': package, 'is_test': is_test}
    
    # === 5. Vendor directory (third-party) ===
    if filepath.startswith('vendor/') or '/vendor/' in filepath:
        return {'category': FileCategory.THIRD_PARTY.value, 'package': package, 'is_test': is_test}
    
    # === 6. Known third-party domains ===
    if first_segment in KNOWN_THIRD_PARTY_DOMAINS:
        return {'category': FileCategory.THIRD_PARTY.value, 'package': package, 'is_test': is_test}
    
    # === 7. Domain-like pattern (third-party) ===
    if _is_valid_domain(first_segment):
        return {'category': FileCategory.THIRD_PARTY.value, 'package': package, 'is_test': is_test}
    
    # === 8. Standard Library (top-level match) ===
    if first_segment in STDLIB_TOP_LEVEL:
        return {'category': FileCategory.STDLIB_PUBLIC.value, 'package': package, 'is_test': is_test}
    
    # === 9. Command-line-arguments (main package) ===
    if first_segment == 'command-line-arguments':
        return {'category': FileCategory.APPLICATION.value, 'package': 'main', 'is_test': is_test}
    
    # === 10. Main package heuristics ===
    if filepath == 'main.go' or filepath.startswith('main/'):
        return {'category': FileCategory.APPLICATION.value, 'package': 'main', 'is_test': is_test}
    
    # === 11. Application code heuristics ===
    special_prefixes = {'_', '.', 'testdata'}
    
    if (
        '.' not in first_segment and
        first_segment not in STDLIB_TOP_LEVEL and
        first_segment not in special_prefixes and
        not first_segment.startswith('_')
    ):
        return {'category': FileCategory.APPLICATION.value, 'package': package, 'is_test': is_test}
    
    # === 12. Fallback: Check if path looks like it could be stdlib ===
    for part in filepath.split('/'):
        if part in STDLIB_TOP_LEVEL:
            return {'category': FileCategory.STDLIB_PUBLIC.value, 'package': package, 'is_test': is_test}
    
    # === Default: Unknown ===
    return {'category': FileCategory.UNKNOWN.value, 'package': package, 'is_test': is_test}

