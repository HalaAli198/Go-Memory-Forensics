def _extract_package_path(func_name: str) -> str:
    """
    Extract the Go import path from a fully-qualified function name.

    Examples:
        "main.main"                                  → "main"
        "fmt.Sprintf"                                → "fmt"
        "net/http.(*Server).ListenAndServe"          → "net/http"
        "github.com/gorilla/mux.(*Router).ServeHTTP" → "github.com/gorilla/mux"
        "wssoft/libs/fs.dirList.func1"               → "wssoft/libs/fs"
        "type..eq.main.Config"                       → inner recursion → "main"
        "runtime/internal/atomic.(*Int64).Load"      → "runtime/internal/atomic"
    """
    if not func_name:
        return None

    # ---- autogenerated wrappers: recurse on inner type path ----
    if func_name.startswith("type.."):
        rest = func_name.split(".", 3)   # ['type', '', 'eq', 'main.Config']
        if len(rest) >= 4:
            return _extract_package_path(rest[3])
        return None

    # ---- strip linker "go:" prefix (rare in pclntab) ----
    if func_name.startswith("go:"):
        func_name = func_name[3:]

    # ---- single-segment name (no slashes) ----
    slash_parts = func_name.split("/")
    if len(slash_parts) == 1:
        dot = func_name.find(".")
        if dot == -1:
            return func_name
        return func_name[:dot] or None

    # ---- multi-segment: prefix/lastSeg.Identifier ----
    prefix = "/".join(slash_parts[:-1])
    last_seg = slash_parts[-1]

    dot_pos = 0
    while True:
        dot_pos = last_seg.find(".", dot_pos)
        if dot_pos == -1:
            return f"{prefix}/{last_seg}"
        next_idx = dot_pos + 1
        if next_idx >= len(last_seg):
            return f"{prefix}/{last_seg[:dot_pos]}"
        nc = last_seg[next_idx]
        if nc.isupper() or nc == '(' or nc == '*':
            return f"{prefix}/{last_seg[:dot_pos]}"
        rest_after = last_seg[next_idx:]
        if '/' in rest_after or '.' in rest_after:
            dot_pos += 1
            continue
        return f"{prefix}/{last_seg[:dot_pos]}"


def _classify_package_path(pkg: str) -> str:
    """
    Classify a bare Go import path (no filename, no identifier).
    Returns a FileCategory value string.
    """
    if not pkg:
        return FileCategory.UNKNOWN.value

    parts = pkg.split("/")
    first = parts[0]

    # runtime core / internal
    if first == "runtime":
        if pkg.startswith("runtime/internal"):
            return FileCategory.RUNTIME_INTERNAL.value
        return FileCategory.RUNTIME_CORE.value

    # internal/*
    if first == "internal":
        for prefix in RUNTIME_INTERNAL_PREFIXES:
            if pkg == prefix or pkg.startswith(prefix + "/"):
                return FileCategory.RUNTIME_INTERNAL.value
        for prefix in STDLIB_INTERNAL_PREFIXES:
            if pkg == prefix or pkg.startswith(prefix + "/"):
                return FileCategory.STDLIB_INTERNAL.value
        return FileCategory.STDLIB_INTERNAL.value

    # crypto/internal, net/internal, vendor/golang.org, etc.
    for prefix in STDLIB_INTERNAL_PREFIXES:
        if pkg == prefix or pkg.startswith(prefix + "/"):
            return FileCategory.STDLIB_INTERNAL.value

    if first == "vendor":
        return FileCategory.THIRD_PARTY.value

    if first in KNOWN_THIRD_PARTY_DOMAINS:
        return FileCategory.THIRD_PARTY.value

    if _is_valid_domain(first):
        return FileCategory.THIRD_PARTY.value

    if first in STDLIB_TOP_LEVEL:
        return FileCategory.STDLIB_PUBLIC.value

    if first in ("main", "command-line-arguments"):
        return FileCategory.APPLICATION.value

    # No dot in first segment → not a domain → application code
    if "." not in first and first not in STDLIB_TOP_LEVEL:
        return FileCategory.APPLICATION.value

    return FileCategory.UNKNOWN.value


def classify_go_func_name(func_name: str) -> dict:
    """
    Classify a Go function by its fully-qualified symbol name.

    Use as a fallback when classify_go_filepath() returns "unknown"
    (source filepath missing from pclntab).

    Returns same dict shape: {'category': str, 'package': str, 'is_test': bool}
    """
    if not func_name or func_name.startswith("<"):
        return {"category": FileCategory.UNKNOWN.value, "package": "", "is_test": False}

    # ---- autogenerated: type..eq.X / type..hash.X ----
    if func_name.startswith("type.."):
        pkg = _extract_package_path(func_name)
        if pkg:
            inner = _classify_package_path(pkg)
            if inner != FileCategory.UNKNOWN.value:
                return {"category": FileCategory.AUTOGENERATED.value,
                        "package": pkg, "is_test": False}
        return {"category": FileCategory.AUTOGENERATED.value,
                "package": "", "is_test": False}

    # ---- go.* — distinguish go.uber.org (third-party) from go.buildid (autogenerated) ----
    if func_name.startswith("go."):
        first_seg = func_name.split("/")[0]
        if not (_is_valid_domain(first_seg) or first_seg in KNOWN_THIRD_PARTY_DOMAINS):
            return {"category": FileCategory.AUTOGENERATED.value,
                    "package": "", "is_test": False}

    # ---- normal classification ----
    pkg = _extract_package_path(func_name)
    if not pkg:
        return {"category": FileCategory.UNKNOWN.value, "package": "", "is_test": False}

    category = _classify_package_path(pkg)
    is_test = "_test" in func_name

    return {"category": category, "package": pkg, "is_test": is_test}

def classify_files_batch(filepaths: list) -> Dict[str, Dict]:
    """
    Classify multiple file paths efficiently.
    
    Args:
        filepaths: List of file paths
        
    Returns:
        Dict mapping filepath -> classification
    """
    cache = {}
    for fp in filepaths:
        if fp not in cache:
            cache[fp] = classify_go_filepath(fp)
    return cache


def get_classification_stats(classifications: Dict[str, Dict]) -> Dict[str, int]:
    """
    Get count of each category.
    
    Args:
        classifications: Dict from classify_files_batch
        
    Returns:
        Dict mapping category name -> count
    """
    stats = {}
    for fp, cls in classifications.items():
        cat = cls['category']
        stats[cat] = stats.get(cat, 0) + 1
    return stats


def get_category_files(classifications: Dict[str, Dict], category: FileCategory) -> list:
    """
    Get all files belonging to a specific category.
    
    Args:
        classifications: Dict from classify_files_batch
        category: FileCategory to filter by
        
    Returns:
        List of file paths in that category
    """
    return [
        fp for fp, cls in classifications.items()
        if cls['category'] == category.value
    ]



