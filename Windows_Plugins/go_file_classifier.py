"""
Go Source File Classifier

Classifies Go source file paths into categories:
- RUNTIME_CORE: Core runtime (runtime/*)
- RUNTIME_INTERNAL: Runtime-critical internal packages
- STDLIB_INTERNAL: Standard library internal packages
- STDLIB_PUBLIC: Public standard library packages
- THIRD_PARTY: Third-party dependencies
- APPLICATION: User application code
- AUTOGENERATED: Compiler-generated code
- UNKNOWN: Unclassifiable

Handles:
- Relative paths (runtime/proc.go)
- Absolute paths (/home/user/go/src/runtime/proc.go)
- GOPATH paths (/home/user/go/pkg/mod/github.com/...)
- Vendor directories
- Module paths with versions (@v1.2.3)
"""

import re
from typing import Dict, Optional, Tuple
from enum import Enum


class FileCategory(Enum):
    """File classification categories."""
    RUNTIME_CORE = "runtime_core"
    RUNTIME_INTERNAL = "runtime_internal"
    STDLIB_INTERNAL = "stdlib_internal"
    STDLIB_PUBLIC = "stdlib_public"
    THIRD_PARTY = "third_party"
    APPLICATION = "application"
    AUTOGENERATED = "autogenerated"
    CGO = "cgo"
    UNKNOWN = "unknown"


